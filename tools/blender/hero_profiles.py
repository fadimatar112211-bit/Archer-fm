"""Per-hero identity profiles for the shared procedural hero builder.

Every hero is generated by the same code path in `build_ranger_source.py`:
identical chibi proportions, identical rig, identical shading network, identical
cicada-sampled animation timing. A profile only changes the things that make a
hero that hero:

* palette (cloth, metal, leather, hair, eyes, energy),
* hair / hood / circlet silhouette,
* cape length and hem,
* weapon meshes and the arm poses for Attack and Special Skill,
* signature effects attached to the weapon and aura bones,
* a few armour accents that change the read at a glance.

Keeping the body construction shared is what makes the four heroes look like one
art team's work instead of four recolours: the silhouettes diverge through
headgear, cape, weapon and FX while the face, hands, boots and proportions stay
pixel-consistent.

Run-time contract used by the builder:

  PROFILES[hero_id]["palette"]        -> palette overrides (hex strings)
  PROFILES[hero_id]["hair"]           -> "spiky" | "short" | "none"
  PROFILES[hero_id]["build_cape"](m)  -> cloth sheets on cloak_a/b/c
  PROFILES[hero_id]["build_armour"](m)   -> optional extra armour
  PROFILES[hero_id]["build_weapon"](m)   -> weapon meshes
  PROFILES[hero_id]["build_fx"](m)       -> attack/skill effects
  PROFILES[hero_id]["attack"](m) / ["skill"](m) -> keyframe lists

`m` is the builder module, so profiles reuse its helpers (`m.sphere`,
`m.sweep`, `m.head_point`, `m.P`, `m.BASE`, `m.merged`, ...). Nothing is
imported from Blender here so this module stays importable by tests and by the
scene validator.
"""

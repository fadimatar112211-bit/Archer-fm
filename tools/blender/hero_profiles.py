def short_cape(m):
    """Waist-length split cape with an angular hem (Flame's knight silhouette)."""
    for index, (bone, v0, v1) in enumerate((
            ("cloak_a", 0.0, 0.40), ("cloak_b", 0.38, 0.74))):
        rows = []
        for i in range(12):
            v = v0 + (v1 - v0) * i / 11.0
            row = []
            for j in range(29):
                u = -1.0 + 2.0 * j / 28.0
                x = u * (0.40 + 0.20 * v)
                y = 0.155 + 0.215 * v + 0.030 * math.sin(u * 8.0) * v
                z = 2.075 - 1.02 * v
                if i >= 9:  # angular, flame-cut hem
                    z += 0.085 * (1.0 - abs(u)) * (i - 9) / 2.0
                row.append(m.Vector((x, y, z)))
            rows.append(row)
        m.grid_sheet(f"Cloak_{index}", rows, ["green", "green_deep"], bone,
                     solidify=(0.024, 1), recalc=False)
    for side, sign in (("L", 1.0), ("R", -1.0)):
        m.grid_sheet(f"Shoulder_Mantle_{side}",
                     _mantle_rows(m, sign, reach=0.32, length=0.85),
                     ["green", "green_deep"], "chest",
                     solidify=(0.020, 1), recalc=False)
    _collar(m)


def tattered_cape(m):
    """Short, ragged, hooded-cape silhouette for the Shadow hunter."""
    for index, (bone, v0, v1) in enumerate((
            ("cloak_a", 0.0, 0.44), ("cloak_b", 0.40, 0.80))):
        rows = []
        for i in range(11):
            v = v0 + (v1 - v0) * i / 10.0
            row = []
            for j in range(27):
                u = -1.0 + 2.0 * j / 26.0
                x = u * (0.40 + 0.30 * v)
                y = 0.155 + 0.255 * v + 0.040 * math.sin(u * 7.0 + 1.3) * v
                z = 2.075 - 1.62 * v
                if i >= 7:
                    z -= 0.16 * (0.5 + 0.5 * math.sin(u * 11.0 + 2.0)) * (i - 6)
                row.append(m.Vector((x, y, z)))
            rows.append(row)
        m.grid_sheet(f"Cloak_{index}", rows, ["green_light", "green"], bone,
                     solidify=(0.022, 1), recalc=False)
    for side, sign in (("L", 1.0), ("R", -1.0)):
        m.grid_sheet(f"Shoulder_Mantle_{side}",
                     _mantle_rows(m, sign, reach=0.30, length=0.82),
                     ["green_light", "green"], "chest",
                     solidify=(0.018, 1), recalc=False)


def _mantle_rows(m, sign, reach=0.34, length=1.0):
    rows = []
    for i in range(5):
        u = i / 4.0
        row = []
        for j in range(9):
            step = j if sign < 0 else 8 - j
            v = step / 8.0
            x = sign * (0.065 + reach * u)
            y = -0.225 + 0.48 * v
            z = 2.090 - 0.085 * math.sin(math.pi * v) - 0.105 * u * length
            z += 0.018 * math.sin(u * 7.0 + v * 3.0)
            row.append(m.Vector((x, y, z)))
        rows.append(row)
    return rows



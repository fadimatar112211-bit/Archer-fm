def shadow_hood(m):
    """Pointed hood with a face opening, plus the lower-face mask."""
    rows, columns = 12, 41

    def line(az):
        a = abs(((az + 180.0) % 360.0) - 180.0)
        if a < 58.0:
            return 21.0 - 4.0 * (a / 58.0) ** 2
        return 21.0 - 48.0 * ((a - 58.0) / 122.0) ** 0.85

    verts, faces, face_materials = [], [], []
    for r in range(rows):
        t = r / (rows - 1.0)
        for j in range(columns):
            az = -180.0 + 360.0 * j / (columns - 1)
            start = line(az)
            el = start + t * (88.0 - start)
            inflate = 0.175 + 0.030 * (1.0 - t)
            verts.append(m.head_point(az, el, inflate))
    for r in range(rows - 1):
        for j in range(columns - 1):
            a = r * columns + j
            faces.append((a, a + 1, a + columns + 1, a + columns))
            face_materials.append(0 if r < rows - 3 else 1)
    pole = len(verts)
    verts.append(m.head_point(0.0, 90.0, 0.185))
    base = (rows - 1) * columns
    for j in range(columns - 1):
        faces.append((base + j, base + j + 1, pole))
        face_materials.append(1)
    m.obj_from("Shadow_Hood", verts, faces, ["green", "green_deep"], "head",
               face_materials=face_materials, recalc=False,
               solidify=(0.020, 1))

    # Sewn brim around the face opening.
    brim = [(az, line(az) + 2.0) for az in range(-57, 58, 6)]
    m.surface_strip("Shadow_Hood_Brim", brim, [0.040] * len(brim),
                    "gold", 0.188, thickness=0.008)

    # Cowl drape: cloth falling from the hood onto both shoulders. Without it
    # the hood reads as a tight cap instead of a hooded cloak.
    for side, sign in (("L", 1.0), ("R", -1.0)):
        rows = []
        for i in range(4):
            u = i / 3.0
            rows.append([m.Vector((
                0.16 * sign + 0.17 * sign * u,
                -0.20 + 0.42 * v,
                2.28 - 0.30 * u + 0.05 * math.sin(u * 6.0 + v * 4.0)))
                for v in (q / 6.0 for q in range(7))])
        m.grid_sheet(f"Shadow_Cowl_{side}", rows, ["green", "green_deep"],
                     "head", solidify=(0.018, 1), recalc=False)

    # Crown peak, matching the folded point behind the head.
    m.sweep("Shadow_Hood_Peak", [
        m.head_point(0.0, 82.0, 0.07),
        m.Vector((0.0, 0.12, 3.22)),
        m.Vector((0.0, 0.28, 3.18)),
        m.Vector((0.0, 0.38, 3.04))],
        [0.130, 0.105, 0.062, 0.010], "green_deep", "head", sides=7,
        thickness=[0.095, 0.078, 0.046, 0.008], tip=True)

    # Folded point hanging behind the head.
    m.sweep("Shadow_Hood_Point", [
        m.head_point(180.0, 62.0, 0.09),
        m.Vector((0.0, 0.50, 2.83)),
        m.Vector((0.0, 0.62, 2.58)),
        m.Vector((0.0, 0.56, 2.34))],
        [0.170, 0.140, 0.080, 0.012], "green_deep", "head", sides=8,
        thickness=[0.130, 0.105, 0.060, 0.010], tip=True)

